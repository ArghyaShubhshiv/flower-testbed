#!/usr/bin/env python3
"""
Generates docker-compose.yml with one `data-init`, one `server`, and
NUM_CLIENTS `client-<i>` services.

Docker Compose YAML has no native loop construct, so to keep the number of
clients parametrized (default 20) this small script materializes the final
compose file. Re-run it whenever you change --num-clients (or the other
hyperparameters) and then `docker compose up --build`.

Usage:
    python3 generate_compose.py --num-clients 20 --alpha 0.5 --local-epochs 5 --num-rounds 50
"""
import argparse
from common.attacks import ATTACK_NAMES, DEFAULT_SCALE

HEADER = """\
# Auto-generated by generate_compose.py -- do not hand-edit the client-N
# blocks; re-run the generator instead.
services:
  data-init:
    image: fl-cifar100-data-init:latest
    build:
      context: .
      dockerfile: data_init/Dockerfile
    volumes:
      - ./data:/data
    environment:
      - DATA_DIR=/data
      - PYTHONUNBUFFERED=1

  server:
    image: fl-cifar100-server:latest
    build:
      context: .
      dockerfile: server/Dockerfile
    ports:
      - "8080:8080"
    depends_on:
      data-init:
        condition: service_completed_successfully
    volumes:
      - ./data:/data
      - ./results:/results
    environment:
      - NUM_CLIENTS={num_clients}
      - LOCAL_EPOCHS={local_epochs}
      - NUM_ROUNDS={num_rounds}
      - FRACTION_FIT=1.0
      - DATA_DIR=/data
      - SEED={seed}
      - RESULTS_DIR=/results
      - PYTHONUNBUFFERED=1
{attack_env}"""

CLIENT_TEMPLATE = """\
  client-{i}:
    image: fl-cifar100-client:latest
{build_section}    depends_on:
      data-init:
        condition: service_completed_successfully
      server:
        condition: service_started
    volumes:
      - ./data:/data
    environment:
      - CLIENT_ID={i}
      - NUM_CLIENTS={num_clients}
      - DIRICHLET_ALPHA={alpha}
      - LOCAL_EPOCHS={local_epochs}
      - BATCH_SIZE={batch_size}
      - LR={lr}
      - SERVER_ADDRESS=server:8080
      - DATA_DIR=/data
      - SEED={seed}
      - MIN_SAMPLES_PER_CLIENT={min_samples_per_client}
      - PYTHONUNBUFFERED=1
{attack_env}"""

FOOTER = ""

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--num-clients", type=int, default=20, help="Number of client containers (default: 20)")
    parser.add_argument("--alpha", type=float, default=0.5, help="Dirichlet alpha controlling data heterogeneity")
    parser.add_argument("--local-epochs", type=int, default=5, help="Local epochs E per client per round (default: 5)")
    parser.add_argument("--num-rounds", type=int, default=50, help="Number of federated rounds")
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--lr", type=float, default=0.01)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--min-samples-per-client", type=int, default=20,
                        help="Guaranteed minimum training examples per client, "
                             "topped up from surplus clients if raw Dirichlet "
                             "sampling would leave a client with too little/no data")
    parser.add_argument("--out", default="docker-compose.yml")
    parser.add_argument("--attack", default="none", choices=ATTACK_NAMES, help="Byzantine attack (default: none)")
    parser.add_argument("--num-byzantine", type=int, default=0, help="Byzantine clients (ids 0..f-1)")
    parser.add_argument("--attack-scale", type=float, default=None, help="Attack strength (per-attack default)")
    parser.add_argument("--attack-start-round", type=int, default=1)
    parser.add_argument("--run-name", default=None, help="Results file name (default: baseline / <attack>_f<f>)")

    args = parser.parse_args()
    if args.attack != "none" and not 0 < args.num_byzantine < args.num_clients:
        parser.error("--attack requires 0 < --num-byzantine < --num-clients")
    if args.attack == "none":
        args.num_byzantine = 0
    scale = args.attack_scale if args.attack_scale is not None else DEFAULT_SCALE.get(args.attack, 1.0)
    run_name = args.run_name or ("baseline" if args.attack == "none" else f"{args.attack}_f{args.num_byzantine}")
    attack_env = (f"      - ATTACK={args.attack}\n      - NUM_BYZANTINE={args.num_byzantine}\n"
                  f"      - ATTACK_SCALE={scale}\n      - ATTACK_START_ROUND={args.attack_start_round}\n")

    out = [HEADER.format(num_clients=args.num_clients, local_epochs=args.local_epochs,
                        num_rounds=args.num_rounds, seed=args.seed,
                        attack_env=attack_env + f"      - RUN_NAME={run_name}\n")]

    for i in range(args.num_clients):
        # Only attach the `build:` block to client-0 to build `fl-cifar100-client:latest` once.
        # All subsequent clients (client-1..N-1) reuse the image produced by client-0.
        build_section = (
            "    build:\n"
            "      context: .\n"
            "      dockerfile: client/Dockerfile\n"
            if i == 0 else ""
        )

        out.append(CLIENT_TEMPLATE.format(
            i=i, build_section=build_section, num_clients=args.num_clients, alpha=args.alpha,
            local_epochs=args.local_epochs, batch_size=args.batch_size,
            lr=args.lr, seed=args.seed,
            min_samples_per_client=args.min_samples_per_client, attack_env=attack_env,
        ))

    out.append(FOOTER)

    with open(args.out, "w") as f:
        f.write("\n".join(out))

    print(f"Wrote {args.out} with {args.num_clients} clients "
          f"(alpha={args.alpha}, local_epochs={args.local_epochs}, num_rounds={args.num_rounds}).")


if __name__ == "__main__":
    main()

